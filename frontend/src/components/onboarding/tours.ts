/**
 * Подсказки туров: один шаг — одна цель на экране и одна фраза про неё.
 *
 * Правила, от которых зависит, будет ли это помогать или раздражать:
 * - **фраза ≤ 8 слов** — это подпись к элементу, а не абзац;
 * - **цель — реальный элемент страницы**, найденный по селектору. Нет его на экране
 *   (не долистали, не загрузилось, роль не та) — шаг молча пропускается: тур не имеет
 *   права зависнуть на цели, которой нет;
 * - **длина тура — по числу смысловых блоков экрана**, а не по круглому числу. На странице
 *   клуба их шесть, и разбивать их на «главные» и «неглавные» было бы враньём: человек всё
 *   равно упрётся в каждый.
 */
export interface CoachStep {
  /** CSS-селектор цели на странице. */
  target: string;
  /**
   * Селектор области ВНУТРИ цели, которая должна остаться затемнённой. Нужен, когда блок
   * подсвечивается целиком, но один его кусок — тема отдельного шага (плашка чата внутри
   * «О клубе»): вырез со скруглением читается как аккуратная выемка, а не как вторая дырка.
   */
  cutout?: string;
  /**
   * Цель визуально уходит В ПОЛНУЮ ШИРИНУ экрана, хотя сам элемент уже (лежит внутри
   * страницы с боковыми отступами, а его содержимое вылезает негативными полями). Тогда
   * дырка считается от кромок экрана, иначе обложка обрезается по бокам.
   */
  fullBleed?: boolean;
  /**
   * Запасная цель, если основной на экране нет. Нужна там, где точная цель условна:
   * строка надёжности не рендерится, пока репутации нет, — но рассказать про надёжность
   * новичку нужно тем более, поэтому подсвечиваем всю панель вместо строки.
   */
  fallbackTarget?: string;
  /** Текст подсказки. Держать в пределах 8 слов. */
  text: string;
  /** Акцентная часть фразы (подсвечивается цветом). Должна встречаться в `text`. */
  accent?: string;
  /**
   * Шаг-задание: пока страница не отдаст `gateSatisfied`, «Далее» не появляется — вместо
   * кнопки стоит эта строка, а затемнение пропускает тапы, иначе задание невыполнимо
   * (решение PO 2026-07-31). Само условие живёт на странице: там уже есть нужные данные.
   */
  gateHint?: string;
  /**
   * Шаг закрывается не кнопкой подсказки, а ИСЧЕЗНОВЕНИЕМ цели: человек нажимает кнопку
   * внутри самой цели (например «Отлично!» на поздравлении), та уходит со страницы — и тур
   * едет дальше. Страница ничего не считает: условие видно по самому DOM.
   */
  awaitDismiss?: boolean;
}

