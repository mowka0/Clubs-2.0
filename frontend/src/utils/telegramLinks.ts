import { openTelegramLink } from '@telegram-apps/sdk-react';

/**
 * Открывает t.me-ссылку (deep link бота, invite link чата) внутри Telegram.
 * openTelegramLink переключает Telegram на нужный экран без закрытия Mini App-контекста;
 * вне Telegram (локальная разработка) — обычная новая вкладка.
 */
export function openTmeLink(url: string): void {
  try {
    if (openTelegramLink.isAvailable()) {
      openTelegramLink(url);
      return;
    }
  } catch (_e) {
    // Не в среде Telegram — падаем на window.open
  }
  window.open(url, '_blank', 'noopener');
}

/**
 * Отдать ссылку другому человеку в один тап: открывает нативный выбор чата Telegram, и
 * выбранному собеседнику уходит сообщение с текстом и ссылкой.
 *
 * Зачем не буфер обмена: скопированную ссылку человек должен ещё куда-то донести — найти
 * админа группы, открыть переписку, вставить. Половина пути теряется на любом из шагов, а
 * ссылка выдачи прав нужна ровно тому, кто без неё бота не починит (правка PO 2026-08-19).
 *
 * Своя сборка, а не `shareURL` из SDK: там внутри те же три строки поверх `openTelegramLink`,
 * а через `openTmeLink` мы бесплатно получаем фолбэк на обычную вкладку вне Telegram.
 *
 * `+` в адресе (у нас им разделён список прав в `?admin=`) `URLSearchParams` кодирует как
 * `%2B`, а пробелы — как `+`; заменяя оставшиеся `+` на `%20`, мы чиним пробелы и не трогаем
 * настоящие плюсы. Ровно так же это делает SDK.
 */
/**
 * Сопроводительный текст к ссылке выдачи прав: его увидит тот, кому её переслали. Одна
 * формулировка на оба места, откуда ссылку отдают (мастер наполнения и таб «Чат»), — человек
 * на той стороне не знает ни про клуб, ни про бота, и объяснять ему должно само сообщение.
 */
export const ADMIN_RIGHTS_SHARE_TEXT =
  'Нужны права администратора для бота клуба. Откройте ссылку и выберите эту группу — ' +
  'Telegram сам предложит выдать боту нужные права.';

export function shareTmeLink(url: string, text: string): void {
  const query = new URLSearchParams({ url, text }).toString().replace(/\+/g, '%20');
  openTmeLink(`https://t.me/share/url?${query}`);
}
