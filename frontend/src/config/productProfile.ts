/**
 * Профиль продукта — единственное место, где живёт разница между двумя способами
 * подать одно и то же приложение:
 *
 * - «плагин к чату» — точка входа это подключённый телеграм-чат, человек попадает
 *   в свой клуб, каталог чужих клубов из навигации убран;
 * - «каталог клубов» — прежняя модель, первый экран это витрина Discovery.
 *
 * Решение PO 2026-08-16 (docs/design/sprint-1.0-chat-pivot.md): продаём плагин к чату.
 *
 * Зачем объект, а не флаг на каждую фичу: развилка одна, и переключается она целиком.
 * Отдельные флаги расползлись бы по экранам, и вернуть каталог значило бы искать их
 * по всему UI. Когда развилка окончательно схлопнется — победивший вариант зашивается
 * в код, а этот файл удаляется целиком.
 *
 * Важно: профиль управляет **навигацией**, а не наличием экранов. Роуты Discovery
 * остаются живыми при любом профиле, иначе внешние ссылки на каталог начнут давать 404.
 */

/** Куда ведёт корневой роут «/». */
type HomeTarget =
  /** В клуб пользователя: один клуб — сразу в него, несколько — в список «Мои клубы». */
  | 'club'
  /** В каталог клубов (прежняя модель). */
  | 'catalog';

interface ProductProfile {
  /** Показывать ли Discovery отдельным табом в нижнем доке. Роут при этом живёт всегда. */
  readonly showDiscoveryTab: boolean;
  /** Куда ведёт «/» — см. HomeTarget. */
  readonly homeTarget: HomeTarget;
}

export const PRODUCT_PROFILE: ProductProfile = {
  showDiscoveryTab: false,
  homeTarget: 'club',
};
