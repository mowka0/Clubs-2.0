/**
 * Профиль продукта — единственное место, где живёт разница между способами подать одно и то же
 * приложение. Две развилки, обе переключаются здесь целиком:
 *
 * 1. Навигация: «плагин к чату» (точка входа — подключённый телеграм-чат, каталог чужих клубов
 *    из навигации убран) против «каталога клубов» (первый экран — витрина Discovery).
 *    Решение PO 2026-08-16 (docs/design/sprint-1.0-chat-pivot.md): продаём плагин к чату.
 * 2. Этап продукта: на этапе 1 «только чат» клубы рождаются из чата друзей, вступают бесплатно
 *    и друг от друга изолированы, поэтому фичи клубов по интересам спрятаны — создание с нуля,
 *    взносы, тип доступа и заявки, категория. Решение PO 2026-10-09
 *    (docs/design/stage-1-scope.md, раздел «Спецификация»). На этапе 2–3 они включаются обратно
 *    одной правкой этого объекта: компоненты, API и query-хуки не удалены, только не показаны.
 *
 * Зачем объект, а не флаг на каждую фичу в своём файле: развилка переключается целиком.
 * Флаги, разбросанные по экранам, пришлось бы потом искать по всему UI. Экраны читают флаги
 * отсюда и своих не заводят. Когда развилка окончательно схлопнется — победивший вариант
 * зашивается в код, а этот файл удаляется.
 *
 * Важно: профиль управляет **показом**, а не наличием экранов. Роуты Discovery остаются живыми
 * при любом профиле, иначе внешние ссылки на каталог начнут давать 404.
 */

/** Куда ведёт корневой роут «/». */
type HomeTarget =
  /** В клуб пользователя: один клуб — сразу в него, несколько — в список «Мои клубы». */
  | 'club'
  /** В каталог клубов (прежняя модель). */
  | 'catalog';

export interface ProductProfile {
  /** Показывать ли Discovery отдельным табом в нижнем доке. Роут при этом живёт всегда. */
  readonly showDiscoveryTab: boolean;
  /** Куда ведёт «/» — см. HomeTarget. */
  readonly homeTarget: HomeTarget;
  /**
   * Создание клуба с нуля (форма CreateClubModal и развилка «из чата / с нуля» за «+ Клуб»).
   * Выключено — «+ Клуб» сразу ведёт к подключению чата: на этапе 1 клуб рождается только из чата.
   */
  readonly showClubCreationFromScratch: boolean;
  /**
   * Платный клуб: взнос, цена, таб «Финансы», шторка взноса, статусы «ждёт оплаты» и
   * «подписка истекла». Подписка владельца ЗА ЧАТ (components/billing) — другое и этим флагом
   * не управляется. Выключено на этапе 1: в дружеском чате вступают бесплатно, общие деньги — сборы.
   */
  readonly showClubDues: boolean;
  /**
   * Тип доступа (открытый / по заявке / приватный) и заявки в клуб, включая «Попроситься»
   * в полный клуб. Выключено на этапе 1: клубы изолированы и создаются на доверии, полный клуб
   * говорит «напиши организатору».
   */
  readonly showAccessTypeAndApplications: boolean;
  /**
   * Категория клуба в тексте (мета карточки «Моих клубов», блок «Нельзя изменить»). Градиент
   * обложки и подсказки тем по категории работают всегда — это не показ категории словом.
   */
  readonly showClubCategory: boolean;
}

export const PRODUCT_PROFILE: ProductProfile = {
  showDiscoveryTab: false,
  homeTarget: 'club',
  // Этап 1 «только чат» (docs/design/stage-1-scope.md) — четыре флага ниже возвращаются на этапе 2.
  showClubCreationFromScratch: false,
  showClubDues: false,
  showAccessTypeAndApplications: false,
  showClubCategory: false,
};
