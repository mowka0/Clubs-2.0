import { miniApp } from '@telegram-apps/sdk-react';

/**
 * Закрывает Mini App. Пользователь возвращается туда, откуда его открыл, — в чат клуба,
 * если приложение открыто кнопкой оттуда.
 *
 * Именно закрывает: свернуть приложение кодом нельзя, среди методов Mini Apps есть только
 * `web_app_close`. Разница ощутима — свёрнутое кнопкой Telegram приложение сохраняет состояние
 * и ждёт в плашке, закрытое стартует с нуля. Поэтому решение оставлено человеку: подсказка
 * показывает и кнопку сворачивания, и этот быстрый выход.
 */
export function closeMiniApp(): void {
  try {
    if (miniApp.close.isAvailable()) miniApp.close();
  } catch (_e) {
    // Хост не поддерживает закрытие — остаёмся в приложении
  }
}
