package com.clubs.city

import java.util.UUID

/**
 * Город из справочника `cities` — единственный допустимый источник города для клуба и профиля.
 * Пополняется только миграцией (выгрузка GeoNames), пользователи города не заводят.
 */
data class City(
    val id: UUID,
    val countryCode: String,
    val name: String,
    /** Регион («Курская область»). Показывается только при [needsRegion]. */
    val region: String?,
    /**
     * У города есть тёзка в другом регионе той же страны (Железногорск, Эрегли) — без региона
     * его не отличить. false = имя уникально, регион не показываем.
     */
    val needsRegion: Boolean,
    /** Показывать в пикере до ввода запроса. Поиск идёт по всему справочнику независимо от флага. */
    val isFeatured: Boolean
)
