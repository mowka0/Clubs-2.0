package com.clubs.event

/**
 * Публикуется, когда менеджер отправил ручное напоминание подтвердить участие (колокольчик в табе
 * «Без ответа», event-stage2-composition.md). Бот-листенер реагирует AFTER_COMMIT: отметка
 * `stage2_reminded_at` должна быть закоммичена ДО ухода DM, иначе упавшая транзакция оставила бы
 * участника с уведомлением, но без отметки — и следующий тап прислал бы ему второе.
 *
 * Несёт готовый список telegram id, а не userId: адресатов уже отфильтровал `markStage2Reminded`
 * (RETURNING по фактически обновлённым строкам), и повторно вычислять их в листенере нельзя —
 * к тому моменту отметка проставлена и предикат «кому можно напомнить» даст пустоту.
 */
data class Stage2ReminderSentEvent(val event: Event, val telegramIds: List<Long>)
