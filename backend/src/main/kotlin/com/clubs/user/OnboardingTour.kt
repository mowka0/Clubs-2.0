package com.clubs.user

/**
 * Экран, у которого есть собственный онбординг.
 *
 * Прохождение считается ПО КАЖДОМУ ЭКРАНУ ОТДЕЛЬНО (решение PO 2026-07-31): пройденный тур
 * страницы клуба ничего не говорит про тур профиля. Раньше на всё был один флаг
 * `users.onboarded_at` — он переехал сюда как [INTRO] (миграция V72).
 *
 * Имя константы — это и есть `tour_key` в БД, поэтому переименование существующего значения
 * равносильно потере прогресса у всех, кто этот тур прошёл. Добавлять новые можно свободно:
 * незнакомый ключ в базе тур просто не найдёт и посчитает непройденным.
 */
enum class OnboardingTour {
    /** Три слайда первого входа. Показываются один раз и только при прямом заходе, без deep-link. */
    INTRO,

    /**
     * Сцена «Ты в клубе!» после самого первого вступления. Не подсказки, а момент награды,
     * поэтому ключ отдельный от [CLUB]: сцена показывается один раз за жизнь аккаунта,
     * а тур по странице клуба идёт следом и закрывается сам по себе.
     */
    WELCOME,

    /** Профиль: заполнение до уровня «Свой». Первый тур после интро — туда ведёт кнопка «Погнали!». */
    PROFILE,

    /** Главная: город, фильтр по интересам, карточка клуба. */
    DISCOVERY,

    /** Страница клуба глазами участника. Для пришедшего по приглашению — самый первый экран вообще. */
    CLUB,

    /**
     * Страница клуба глазами ВЛАДЕЛЬЦА, сразу после создания первого клуба. Отдельный ключ,
     * а не флаг внутри [CLUB]: погружение здесь подробнее (те же блоки плюс вход в управление),
     * и человек, успевший пройти участнический тур в чужом клубе, всё равно должен получить
     * владельческий в своём.
     */
    CLUB_OWNER,

    /** Настройки клуба: что здесь меняется, а что уже не поменять. Только владельцу. */
    CLUB_MANAGE,

    /** «Мои клубы»: свои клубы и создание своего. */
    MY_CLUBS,

    /** «Активности»: встречи и складчины, подтверждение участия. */
    ACTIVITIES;

    companion object {
        /**
         * Разбор ключа из URL. Возвращает null на неизвестном значении, а не бросает: вызывающий
         * превращает это в 400. Через `valueOf` было бы `IllegalArgumentException` → 500.
         */
        fun parse(raw: String): OnboardingTour? =
            entries.firstOrNull { it.name.equals(raw, ignoreCase = true) }
    }
}
