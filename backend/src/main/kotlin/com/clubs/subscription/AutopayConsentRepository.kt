package com.clubs.subscription

import java.util.UUID

/**
 * Откуда пришло согласие на автосписание; [wording] — текст, который человек видел рядом с отметкой.
 * Он хранится в строке истории: формулировка на экране может смениться, а разбор спора идёт по той,
 * под которой согласие дали. Текст отметки на форме — дословно по требованию Robokassa (2026-10-05).
 */
enum class ConsentSource(val wording: String) {
    /** Отметка на форме оплаты (шит); по умолчанию снята. */
    CHECKOUT("Я согласен на автоматические списания согласно условиям оферты"),
    /** Ползунок на странице клуба: включил = согласие, выключил = отзыв. */
    TOGGLE("Продлевать автоматически"),
}

/** Факт согласия или отказа для записи в историю (таблица autopay_consent, V102). */
data class AutopayConsent(
    val clubId: UUID,
    val userId: UUID,
    val source: ConsentSource,
    /** true = согласие дано, false = отметка снята при чекауте или ползунок выключен. */
    val granted: Boolean,
    /** Материнский счёт, на чекауте которого сделана отметка; null у ползунка. */
    val paymentId: UUID? = null,
    /** Подписка на момент действия; null у первого чекаута — её ещё нет. */
    val subscriptionId: UUID? = null,
)

/**
 * История согласий на автоматические списания — условие Robokassa для рекуррентных платежей.
 * Только запись: строки не правятся и не удаляются, в логику продукта не входят (ползунок живёт
 * на подписке, отметка чекаута — на счёте).
 */
interface AutopayConsentRepository {
    /** Пишет факт в текущей транзакции — откатывается вместе с чекаутом или переключением. */
    fun record(consent: AutopayConsent)
}
