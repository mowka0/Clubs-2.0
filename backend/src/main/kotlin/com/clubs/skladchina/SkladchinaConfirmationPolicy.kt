package com.clubs.skladchina

/**
 * Сроки сверки оплат (V89, docs/modules/skladchina.md § «Подтверждение оплат организатором»).
 * Все три окна — про одно: сколько ждём человека, прежде чем решить за него.
 */
object SkladchinaConfirmationPolicy {

    /**
     * Сколько есть у участника на чек после того, как организатор не нашёл его платёж.
     * 48 часов — как окно оспаривания явки (`ATTENDANCE_DISPUTE_WINDOW_MINUTES`): спор о деньгах
     * не срочнее спора о том, был ли человек на встрече. Молчание после окна = −40.
     */
    const val RECEIPT_WINDOW_HOURS = 48L

    /**
     * Сколько ждём организатора с решением по присланному чеку. Не дождались — спор закрывается
     * НЕЙТРАЛЬНО: участник своё сделал (прислал доказательство), вины за ним нет.
     */
    const val DISPUTE_RESOLUTION_DAYS = 7L

    /**
     * Сколько после дедлайна ждём, что организатор придёт сверять деньги. Не пришёл — сбор сводит
     * шедулер по правилу «кто ответил, тому верим» (редакция PO 2026-09-09): заявленные оплаты
     * засчитываются, неразобранные заявки на отказ одобряются, молчание стоит −40. Так цена
     * неответа не зависит от расторопности организатора.
     */
    const val ABANDONED_CONFIRMATION_DAYS = 7L
}
