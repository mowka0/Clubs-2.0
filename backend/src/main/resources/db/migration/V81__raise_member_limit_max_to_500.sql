-- Потолок участников клуба поднят с 80 до 500.
--
-- Причина: разворот на плагин к чату (решение PO 2026-08-16). Клуб создаётся из
-- телеграм-чата и должен вместить всех его участников, а типовое сообщество — от
-- пятидесяти до пятисот человек. Прежний потолок 80 отсекал бы людей на 81-м
-- вступившем, причём в самый неудачный момент: бот уже работает, люди отвечают
-- на опрос, и часть из них молча упирается в лимит.
--
-- Минимум остаётся 1 (ослаблен в V56 ради теста заполняемости полного клуба).

ALTER TABLE clubs DROP CONSTRAINT IF EXISTS clubs_member_limit_check;
ALTER TABLE clubs ADD CONSTRAINT clubs_member_limit_check
    CHECK (member_limit >= 1 AND member_limit <= 500);

COMMENT ON COLUMN clubs.member_limit IS
    'Лимит числа участников клуба, от 1 до 500 (CHECK). Потолок поднят с 80 в V81 '
    'под клубы, создаваемые из телеграм-чата: чат сообщества обычно 50–500 человек.';
