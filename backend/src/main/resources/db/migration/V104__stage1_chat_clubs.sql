-- V104: этап 1 «только чат» (docs/design/stage-1-scope.md, решения PO 2026-10-09). Только данные.
--
-- 1. Лимит участников клуба из чата = потолок 500. Раньше он выставлялся по размеру чата в момент
--    привязки, и каждый новый человек, добавленный в группу, упирался в «клуб полон» и попадал в
--    заявки (на проде так заполнены все клубы с чатом). Новые клубы из чата получают 500 в коде;
--    здесь — существующие. Организатор может поставить меньше в «Настройках».
-- 2. Клубы «по заявке» (closed) становятся private, как все клубы из чата: на этапе 1 заявок в
--    интерфейсе нет, и вступить в closed-клуб стало бы нечем (на проде все три такие клуба — с чатом).
--    На этапе 2 тип доступа выберут сами.
-- Клуб из чата узнаётся по привязке ИЛИ по private: отвязанный клуб из чата привязку теряет, а private
-- рождается только из чата.

UPDATE clubs
SET member_limit = 500, updated_at = now()
WHERE (access_type = 'private' OR id IN (SELECT club_id FROM club_chat_links))
  AND member_limit < 500;

-- Заявочный код («через одобрение») у private ведёт себя как прямой: уже разосланные ссылки, которые
-- обещали одобрение организатора, после смены типа впускали бы сразу. Сбрасываем — новый код
-- сгенерируется лениво при следующем «Пригласить» (проверка безопасности 2026-10-09).
UPDATE clubs
SET apply_invite_code = NULL
WHERE access_type = 'closed';

UPDATE clubs
SET access_type = 'private', updated_at = now()
WHERE access_type = 'closed';

COMMENT ON COLUMN clubs.member_limit IS
    'Лимит числа участников клуба, от 1 до 500 (CHECK). Клуб из телеграм-чата получает потолок 500 (V104): '
    'в клубе те, кто в чате, а лимит по размеру чата упирал новых людей группы в «клуб полон». Организатор может поставить меньше.';
