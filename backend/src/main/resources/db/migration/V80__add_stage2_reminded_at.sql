-- V80: ручное напоминание «подтвердите участие» на Этапе 2 (event-stage2-composition.md § «Что дальше»).
-- Организатор (или со-организатор) жмёт колокольчик у не ответившего — бот шлёт ему DM с кнопкой
-- подтверждения. Отметка нужна для двух вещей сразу:
--   1) дедупликация: одно напоминание на участника на событие, повторный тап ничего не отправит;
--   2) подпись в интерфейсе «напомнили в 18:42» — организатор видит, кого уже пинали.
--
-- Отметка пер-участник (в event_responses), а НЕ пер-событие: прежняя events.confirm_reminder_sent
-- (V21) дедуплицировала АВТОМАТИЧЕСКУЮ рассылку по всем сразу и была удалена вместе с ней (V51,
-- решение PO 2026-07-08 «лишний пинг»). Здесь рассылки по расписанию нет — есть адресное действие
-- человека, поэтому и счёт ведётся по конкретному участнику.

ALTER TABLE event_responses ADD COLUMN IF NOT EXISTS stage2_reminded_at TIMESTAMPTZ;

COMMENT ON COLUMN event_responses.stage2_reminded_at IS
    'Когда организатор отправил участнику ручное напоминание подтвердить участие на Этапе 2 (NULL = не напоминали). Одно напоминание на участника на событие: непустое значение блокирует повторную отправку.';
