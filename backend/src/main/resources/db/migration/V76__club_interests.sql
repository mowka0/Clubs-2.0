-- Темы клуба: второй уровень описания поверх категории-полки.
--
-- Категория (club_category, 8 значений) — полка, по ней работают фильтры каталога и ранг L3.
-- Тема — что стоит на полке: «Спорт» + {бег, марафон} против «Спорт» + {бокс, единоборства}.
-- Словарь общий с интересами профиля намеренно: сопоставлять человека и клуб можно только
-- в одном пространстве имён. Спека: docs/modules/club-interests.md.
--
-- Модель взята из отменённой V60__onboarding_taxonomy.sql (ветка feature/onboarding, коммит
-- 947b3be) — она умерла вместе с онбордингом-с-вопросами, но таксономия и затравка живы.

-- ── Тема знает свою полку ───────────────────────────────────────────────────────────────
ALTER TABLE interests ADD COLUMN IF NOT EXISTS category club_category;
COMMENT ON COLUMN interests.category IS
    'Категория-полка темы (enum club_category). NULL = тема ещё не разложена по полкам — так '
    'выглядят интересы, введённые в профиле свободным вводом. Такие не попадают в чипы при '
    'разметке клуба, но живут в профиле и участвуют в поиске.';

-- ── Отдельный счётчик употребления клубами ──────────────────────────────────────────────
-- usage_count считает ПОЛЬЗОВАТЕЛЕЙ и сортирует автодополнение профиля. Сортировать по нему
-- же подсказки для клубов нельзя: частый интерес людей ≠ частая тема клубов («нетворкинг»
-- в профиле у многих, клубов с такой темой единицы).
ALTER TABLE interests ADD COLUMN IF NOT EXISTS club_usage_count INTEGER NOT NULL DEFAULT 0;
COMMENT ON COLUMN interests.club_usage_count IS
    'Сколько клубов сейчас размечены этой темой (инкремент/декремент при правке тем клуба, '
    'не ниже 0). Сортировка чипов при разметке клуба. Считается отдельно от usage_count, '
    'который остаётся про пользователей.';

CREATE INDEX IF NOT EXISTS idx_interests_category_club_usage
    ON interests (category, club_usage_count DESC);
COMMENT ON INDEX idx_interests_category_club_usage IS
    'Топ-темы полки для чипов при создании и редактировании клуба.';

-- ── Разметка клуба темами (0–7) ─────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS club_interests (
    club_id     UUID NOT NULL REFERENCES clubs (id) ON DELETE CASCADE,
    -- RESTRICT, а не CASCADE: вычистка строки словаря не должна молча оторвать клубу тему.
    -- Удаление самого клуба темы уносит (CASCADE выше) — там это ожидаемо.
    interest_id UUID NOT NULL REFERENCES interests (id) ON DELETE RESTRICT,
    -- Порядок задаёт организатор, и он значим: карточка каталога показывает только первые темы.
    -- Отдельная колонка, а не сортировка по created_at: все связи пишутся одной транзакцией, а
    -- now() в ней возвращает время НАЧАЛА транзакции — время у всех строк совпадает до микросекунды,
    -- и порядок разметки схлопывался бы в алфавитный.
    position    SMALLINT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (club_id, interest_id)
);
COMMENT ON TABLE club_interests IS
    'Связь M:N «клуб — тема» (0–7 тем на клуб). Уточняет категорию клуба: по темам работает '
    'поиск каталога и, начиная со среза 2, подбор клубов под интересы человека.';
COMMENT ON COLUMN club_interests.club_id IS 'Клуб (FK clubs.id, каскадное удаление вместе с клубом).';
COMMENT ON COLUMN club_interests.interest_id IS
    'Тема (FK interests.id, ON DELETE RESTRICT — строку словаря нельзя удалить, пока она '
    'кому-то назначена).';
COMMENT ON COLUMN club_interests.position IS
    'Позиция темы в наборе клуба (0 = главная). Задаётся порядком, в котором организатор выбрал '
    'темы; карточка каталога показывает первые из них.';
COMMENT ON COLUMN club_interests.created_at IS
    'Когда связь была записана. Набор тем сохраняется перезаписью целиком, поэтому у всех тем '
    'клуба это время последней правки разметки, а не первого назначения.';

CREATE INDEX IF NOT EXISTS idx_club_interests_interest ON club_interests (interest_id);
COMMENT ON INDEX idx_club_interests_interest IS
    'Обратный проход «по теме — какие клубы»: поиск каталога и подбор среза 2.';

