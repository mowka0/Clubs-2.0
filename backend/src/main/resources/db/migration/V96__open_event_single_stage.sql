COMMENT ON COLUMN events.participant_limit IS
    'Максимум участников — ПОТОЛОК мест (V86): сверх него голос «Иду» встаёт в очередь на замену. NULL = открытая встреча (V96, модель v3): без мест, очереди, дедлайна набора и второго этапа — голос «Пойду» сразу кладёт в состав, а репутация за посещение не меняется. У обычной встречи обязателен — NULL читают как маркер открытой встречи репутация (ReputationService), обязательства при выходе из клуба и статистика открытых встреч.';

COMMENT ON COLUMN events.stage_2_triggered IS
    'TRUE = набор состава уже закрывался (дедуп тика, срабатывающего за stage2_lead_minutes до старта). У открытой встречи (participant_limit IS NULL) навсегда FALSE (V96): дедлайна набора у неё нет, голосование идёт до самого старта.';

COMMENT ON COLUMN event_responses.stage_2_vote IS
    'Место в составе (enum stage_2_vote): confirmed = в составе; waitlisted = в очереди (места кончились); declined = отказался от занятого места; expired_no_confirm = легаси-статус двухэтапки — не подтвердил до старта. NULL = места не занимает. С V83/V96 пишется ГОЛОСОМ Этапа 1 у обоих форматов: «Иду» → confirmed (у встречи с местами — waitlisted, если потолок исчерпан), любой другой голос → NULL.';

COMMENT ON COLUMN event_responses.final_status IS
    'Итоговый статус участия (enum final_status): confirmed = в составе (по нему идут отметка явки и репутация); waitlisted = в очереди; declined = отказался; expired_no_confirm = легаси-статус двухэтапки. NULL = места не занимает. У открытой встречи (V96) достижимы только confirmed и NULL: expired_no_confirm ей больше не выставляется, а отказ — это голос «Не пойду».';
