-- Дедупликация DM «подписка истекает» (SubscriptionScheduler).
-- Раньше планировщик отбирал ВСЕ active-членства с окном доступа в ближайшие 3 дня и слал
-- напоминание на каждом тике: при ежедневном кроне участник получал три одинаковых DM подряд
-- (за 3 дня, за 2, за 1), при частом кроне staging — на каждом тике. Теперь напоминаний ровно два
-- (за 3 дня и за 1 день), а колонка помнит последний отправленный порог в рамках ТЕКУЩЕГО окна
-- доступа и сбрасывается в NULL везде, где переписывается subscription_expires_at (взнос получен,
-- «Своя дата», повторное вступление, кик).
ALTER TABLE memberships ADD COLUMN IF NOT EXISTS expiry_reminder_days_left INTEGER;

COMMENT ON COLUMN memberships.expiry_reminder_days_left IS
    'Порог последнего отправленного DM «подписка истекает» в текущем окне доступа, в днях до его конца: 3 = ушло напоминание за 3 дня, 1 = ушло последнее (за 1 день), NULL = ни одного (новое или продлённое окно). Сбрасывается вместе с записью subscription_expires_at. Дедуп планировщика: без него DM уходил на каждом тике крона.';
