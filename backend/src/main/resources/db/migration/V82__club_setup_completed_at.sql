-- Отметка «мастер наполнения пройден» для клуба, рождённого из чата.
--
-- Зачем колонка, а не вывод по данным: раньше признаком «клуб не заполнен» служило
-- отсутствие города (city_id IS NULL), и баннер «Клуб ещё не заполнен» исчезал сразу после
-- второго шага мастера — описание, темы и обложку человек уже не мог доделать, дверь в мастер
-- пропадала (баг PO 2026-08-19). Пропускать шаги при этом разрешено, поэтому по заполненности
-- полей завершение мастера не вычисляется: нужен факт «дошёл до конца».
--
-- Хранится на сервере, а не в localStorage: признак принадлежит клубу, и с другого устройства
-- владелец должен видеть то же самое.

ALTER TABLE clubs ADD COLUMN IF NOT EXISTS setup_completed_at TIMESTAMPTZ;

-- Существующие клубы созданы формой, где все поля заполняются сразу, — мастер им не нужен.
-- Без этого backfill'а баннер вылез бы на каждом клубе в проде.
UPDATE clubs SET setup_completed_at = created_at WHERE setup_completed_at IS NULL;

COMMENT ON COLUMN clubs.setup_completed_at IS
    'Когда владелец закончил мастер наполнения клуба из чата (NULL = мастер не пройден, '
    'на странице клуба висит баннер «Клуб ещё не заполнен»). Клубы, созданные формой, '
    'получают отметку сразу при создании: форма и есть заполнение.';
