-- Обложка клуба — отдельное поле от аватара.
-- До этого шапка страницы клуба растягивала avatar_url, поэтому одна картинка обслуживала две
-- разные роли: кружок 70px и баннер во всю ширину. Смена аватара молча меняла и обложку.
ALTER TABLE clubs ADD COLUMN cover_url TEXT;

COMMENT ON COLUMN clubs.cover_url IS 'URL обложки в шапке страницы клуба (NULL = рисуем градиент по категории).';
-- Уточняем назначение аватара: комментарий из V44 описывал его как «аватар/обложка».
COMMENT ON COLUMN clubs.avatar_url IS 'URL аватара клуба — кружок в шапке, карточках каталога и лентах (NULL = монограмма из названия).';

-- У уже созданных клубов обложка фактически равнялась аватару. Переносим значение, чтобы
-- разделение полей не поменяло вид существующих клубов; дальше они живут независимо.
UPDATE clubs SET cover_url = avatar_url WHERE avatar_url IS NOT NULL;
