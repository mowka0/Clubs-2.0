-- V99: бесплатный период чата вместо одной бесплатной встречи (решение PO 2026-09-15).
--
-- Было: одна бесплатная встреча на чат, отменённая до старта возвращалась (V97, R4/R5).
-- Стало: после ПЕРВОЙ созданной встречи чат живёт бесплатно BILLING_TRIAL_DAYS дней (по умолчанию
-- 15), дальше — подписка. Причина: одна встреча — один опыт, за него привычки не возникает; счёт
-- приходит человеку, который успел провести две-три встречи и увидел, что бот снял с него рутину.
-- Срок вместо счётчика встреч — у всех одинаковый бесплатный период (счётчик давал клубу «раз в
-- месяц» целый квартал бесплатно, а ежедневным тренировкам — три дня).
--
-- Таблица та же (признак живёт по chat_id и переживает отвязку чата, удаление клуба и переезд
-- группы — R6), меняется смысл полей.
ALTER TABLE chat_free_meeting RENAME TO chat_trial;
ALTER TABLE chat_trial RENAME COLUMN used_at TO started_at;
ALTER TABLE chat_trial RENAME COLUMN event_id TO first_event_id;

-- Возврат бесплатной встречи отменой (R5) больше не нужен: срок идёт по календарю и от отмены
-- не зависит.
ALTER TABLE chat_trial DROP COLUMN released_at;

-- Дедуп DM о конце бесплатного периода — как expiry_reminder_days_left у memberships (V77):
-- без него напоминание уходило бы на каждом тике крона.
ALTER TABLE chat_trial ADD COLUMN reminder_days_left INTEGER;

COMMENT ON TABLE chat_trial IS
    'Бесплатный период чата Telegram: строка появляется с первой созданной встречей и задаёт, до какого момента клуб этого чата живёт без подписки (billing.trial-days). Переживает отвязку чата, удаление клуба и повторное подключение того же чата новым клубом — второй бесплатный период по тому же chat_id не выдаётся.';
COMMENT ON COLUMN chat_trial.chat_id IS
    'Чат Telegram, которому выдан бесплатный период (первичный ключ). При переезде группы в супергруппу обновляется листенером ChatIdMigratedEvent.';
COMMENT ON COLUMN chat_trial.club_id IS
    'Клуб, чья первая встреча запустила отсчёт. Без FK: клуб может быть удалён, а срок продолжает идти по чату.';
COMMENT ON COLUMN chat_trial.first_event_id IS
    'Первая созданная встреча чата — та, с которой пошёл отсчёт. Без FK по той же причине; хранится ради разбора спорных случаев.';
COMMENT ON COLUMN chat_trial.started_at IS
    'Момент создания первой встречи. Бесплатный период идёт до started_at + billing.trial-days; отмена встречи его НЕ возвращает (V99).';
COMMENT ON COLUMN chat_trial.reminder_days_left IS
    'Порог последнего отправленного DM о конце бесплатного периода, в днях до конца: 3 = ушло напоминание за 3 дня, 1 = ушло последнее, NULL = ни одного. Дедуп планировщика (как memberships.expiry_reminder_days_left, V77).';
