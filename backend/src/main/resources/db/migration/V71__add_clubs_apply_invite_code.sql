-- Второй инвайт-код клуба: по нему вступление идёт ЧЕРЕЗ ЗАЯВКУ, а не напрямую.
--
-- Зачем два кода, а не флаг в ссылке. Приглашение из «Отправить в Telegram» и ссылка из
-- «Скопировать ссылку» обязаны вести себя по-разному в клубе «по заявке»: первая — на одобрение
-- организатором, вторая — сразу в клуб (осознанный обход, о котором в интерфейсе написано прямо).
-- Будь код один, разница жила бы только в параметре deep-link'а — получатель «заявочной» ссылки
-- обошёл бы одобрение, стерев параметр и оставив код. Разные коды делают правило неподделываемым:
-- из «заявочной» ссылки прямой код не вывести.
ALTER TABLE clubs ADD COLUMN apply_invite_code VARCHAR(255) UNIQUE;

COMMENT ON COLUMN clubs.apply_invite_code IS
    'Инвайт-код «через заявку» для приглашений из Telegram (NULL = ещё не сгенерирован, генерируется лениво). В клубе с access_type=closed вход по нему требует одобрения организатора; в open/private ведёт себя как invite_link — там одобрения не существует.';
