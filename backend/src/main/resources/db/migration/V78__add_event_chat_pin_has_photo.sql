-- Фото встречи в посте живого закрепа (PO 2026-08-08: в личку картинка уходила, в чат — нет).
-- Пост с фото — это сообщение-картинка с подписью, и правки статуса ему нужны через
-- editMessageCaption, а не editMessageText (у фото нет текста — Telegram отвечает ошибкой).
-- Флаг помнит, чем именно пост вышел: фото могло не отправиться (длинная подпись, недоступная
-- картинка) и деградировать до текста, а закрепы событий, созданных до этой правки, текстовые
-- по определению — им правки текстом (DEFAULT FALSE и есть их значение).
ALTER TABLE event_chat_pins ADD COLUMN IF NOT EXISTS has_photo BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN event_chat_pins.has_photo IS
    'TRUE = сообщение-статус отправлено картинкой встречи с подписью (правки идут через editMessageCaption), FALSE = обычным текстом (editMessageText). Фиксирует фактический вид поста: фото могло не уйти и деградировать до текста.';
