-- Закреплённая в чате ссылка на клуб: чтобы участники не искали приложение по истории переписки.
-- Пост «Вступить в клуб» бот отправлял при первичной привязке и раньше (слайс 5), но не закреплял —
-- сообщение уезжало вверх и через неделю его никто не находил.
ALTER TABLE club_chat_links ADD COLUMN IF NOT EXISTS club_pin_message_id BIGINT;

COMMENT ON COLUMN club_chat_links.club_pin_message_id IS
    'ID закреплённого в чате поста со ссылкой на клуб. NULL = не закреплён (чат привязан до '
    'появления закрепа, организатор снял закреп вручную или у бота нет права закреплять).';

-- Слепок настройки группы «История чата для новых участников», как и права бота рядом.
-- Когда история скрыта, новый участник не видит НИЧЕГО, отправленного до его вступления —
-- ни переписки, ни закреплённых сообщений (закреп встречи и ссылка на клуб для него не существуют).
-- Изменить настройку бот не может (в Bot API нет метода), только владелец группы вручную.
ALTER TABLE club_chat_links ADD COLUMN IF NOT EXISTS history_visible_to_new_members BOOLEAN;

COMMENT ON COLUMN club_chat_links.history_visible_to_new_members IS
    'Видна ли новым участникам история чата (слепок getChat.has_visible_history, обновляется при '
    'привязке и по кнопке «Проверить права»). FALSE = новички не видят закрепы и переписку до '
    'вступления. NULL = ещё не проверяли (чат привязан до появления проверки).';
